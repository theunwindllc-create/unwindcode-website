import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {writeFile} from 'node:fs/promises';
const {default:puppeteer}=await import(pathToFileURL(process.env.ATLAS_PUPPETEER_PATH));
const origin=process.env.ATLAS_PREVIEW_URL||'http://localhost:52498';
const browser=await puppeteer.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,timeout:60000,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const checks=[];const pass=name=>{checks.push(name);console.log('PASS',name)};
const delay=ms=>new Promise(r=>setTimeout(r,ms));
try{
 const page=await browser.newPage();await page.setViewport({width:1440,height:1000});
 await page.goto(`${origin}/organisms/visual-cortex`,{waitUntil:'networkidle0'});
 await page.waitForFunction(()=>document.querySelector('[data-atlas-image]').getAnimations().some(a=>a.playState==='running'));
 await page.click('#atlas-motion-toggle');
 await page.waitForFunction(()=>document.documentElement.classList.contains('motion-paused'));
 const time=await page.$eval('[data-atlas-image]',e=>e.getAnimations()[0].currentTime);
 await delay(300);
 assert.equal(await page.$eval('[data-atlas-image]',e=>e.getAnimations()[0].currentTime),time);
 assert.ok(await page.$$eval('img[data-atlas-static-src]',els=>els.length>0&&els.every(e=>e.getAttribute('src')===e.dataset.atlasStaticSrc)));
 pass('Manual pause freezes art time and switches all external animated SVGs to stills');
 await page.click('#atlas-motion-toggle');
 await page.waitForFunction(()=>document.querySelector('[data-atlas-image]').getAnimations().some(a=>a.playState==='running'));
 await page.evaluate(()=>scrollTo({top:document.body.scrollHeight,behavior:'instant'}));
 await page.waitForFunction(()=>document.querySelector('[data-atlas-image]').getAnimations().every(a=>a.playState!=='running'));
 pass('Offscreen artwork suspends');
 await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
 await page.emulateMediaFeatures([{name:'prefers-reduced-motion',value:'reduce'}]);
 await page.waitForFunction(()=>document.documentElement.dataset.atlasMotionState==='reduced');
 assert.ok(await page.$eval('#atlas-motion-toggle',e=>e.disabled));
 assert.equal(await page.$eval('[data-atlas-image]',e=>e.getAnimations().length),0);
 await page.emulateMediaFeatures([{name:'prefers-reduced-motion',value:'no-preference'}]);
 await page.waitForFunction(()=>document.querySelector('[data-atlas-image]').getAnimations().some(a=>a.playState==='running'));
 pass('OS reduced motion changes dynamically and restores the saved choice');
 await page.goto(`${origin}/home`,{waitUntil:'networkidle0'});
 await page.waitForFunction(()=>document.querySelector('#neural-canvas').dataset.fieldState==='active');
 await page.click('#atlas-motion-toggle');
 await page.waitForFunction(()=>document.querySelector('#neural-canvas').dataset.fieldState==='paused');
 assert.ok(await page.evaluate(()=>document.getAnimations().every(a=>a.playState!=='running')));
 await page.click('#atlas-motion-toggle');
 await page.waitForFunction(()=>document.querySelector('#neural-canvas').dataset.fieldState==='active');
 await page.evaluate(()=>scrollTo({top:document.body.scrollHeight,behavior:'instant'}));
 await page.waitForFunction(()=>document.querySelector('#neural-canvas').dataset.fieldState==='paused');
 pass('Legacy console canvas obeys pause, resume, and offscreen suspension');
 await page.goto(`${origin}/organisms/infinity-mirror/experience`,{waitUntil:'networkidle0'});
 await page.click('#atlas-motion-toggle');
 await page.waitForFunction(()=>document.documentElement.classList.contains('motion-paused'));
 await delay(100);
 assert.ok(await page.evaluate(()=>document.getAnimations().every(a=>a.playState!=='running')));
 assert.ok(await page.$$eval('img[data-atlas-static-src]',els=>els.every(e=>e.getAttribute('src')===e.dataset.atlasStaticSrc)));
 pass('Mirror experience CSS and external diagrams obey shared pause');
 await page.goto(`${origin}/architecture`,{waitUntil:'networkidle0'});
 assert.equal(await page.$eval('#atlas-motion-toggle',e=>e.getAttribute('aria-pressed')),'true');
 pass('Pause persists across routes');
 await writeFile(new URL('../artifacts/living-atlas-qa/phase2-motion-report.json',import.meta.url),JSON.stringify({checks},null,2));
}finally{await browser.close();}
